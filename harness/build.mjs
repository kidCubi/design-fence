#!/usr/bin/env node
/**
 * Makes the plugins, each one file with what it runs, since the agent tools
 * copy a plugin out of the repository (Claude Code's and Codex's cache,
 * OpenCode's plugins folder), where `../lib` is not:
 *
 *     harness/plugin/hook.mjs            ← lib/ + harness/src/claude-codex.mjs
 *     harness/opencode/design-fence.js   ← lib/ + harness/src/opencode.mjs
 *
 *     node harness/build.mjs            writes them
 *     node harness/build.mjs --check    says which differ from a new build (exit 1)
 *
 * `lib/`'s modules go in one after the other, without their imports of each
 * other and their `export`s (OpenCode loads every export of the file as a
 * plugin); node's modules are imported once, at the top. The generated files
 * are committed: the tools install from the repository.
 */

import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const HOME = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

/** `lib/`'s modules the plugins carry, each after those it imports. */
const LIB = ['lib/git.mjs', 'lib/fence.mjs', 'lib/specs.mjs', 'lib/route.mjs', 'lib/agent-hooks.mjs'];

/** Each plugin's file, from its adapter. */
export const TARGETS = {
  'harness/plugin/hook.mjs': 'harness/src/claude-codex.mjs',
  'harness/opencode/design-fence.js': 'harness/src/opencode.mjs',
};

const IMPORT = /^import\s+([\s\S]*?)\s+from\s+'([^']+)';[ \t]*\n/gm;

/** One file: `lib/` and the adapter, node's imports merged at the top. */
export function bundle(entry, home = HOME) {
  const defaults = new Map();
  const named = new Map();
  const add = (map, from, name) => map.set(from, new Set([...(map.get(from) ?? []), name]));
  const parts = [];
  let shebang = '';
  for (const file of [...LIB, entry]) {
    let text = fs.readFileSync(path.join(home, file), 'utf8');
    if (text.startsWith('#!')) {
      shebang = text.slice(0, text.indexOf('\n') + 1);
      text = text.slice(shebang.length);
    }
    text = text.replace(IMPORT, (all, what, from) => {
      if (from.startsWith('.')) {
        return '';
      }
      const braces = what.match(/\{([\s\S]*)\}/);
      if (braces) {
        braces[1].split(',').map(name => name.trim()).filter(Boolean).forEach(name => add(named, from, name));
      }
      const head = what.replace(/\{[\s\S]*\}/, '').replace(/,\s*$/, '').trim();
      if (head) {
        add(defaults, from, head);
      }
      return '';
    });
    if (file !== entry) {
      text = text.replace(/^export (?=(?:async )?function |const |let |class )/gm, '');
    }
    parts.push(`// ---- ${file}\n\n${text.trim()}\n`);
  }
  const modules = [...new Set([...defaults.keys(), ...named.keys()])].sort();
  const imports = modules.flatMap(from => [
    ...[...(defaults.get(from) ?? [])].map(name => `import ${name} from '${from}';`),
    ...(named.has(from) ? [`import {${[...named.get(from)].sort().join(', ')}} from '${from}';`] : []),
  ]);
  const notice = `// Generated by harness/build.mjs from ${[...LIB, entry].join(', ')}: do not edit, run \`node harness/build.mjs\`.`;
  return `${shebang}${notice}\n\n${imports.join('\n')}\n\n${parts.join('\n')}`;
}

/** Every plugin's file, as a new build makes it: `{path: text}`. */
export const build = (home = HOME) => Object.fromEntries(Object.entries(TARGETS).map(([target, entry]) => [target, bundle(entry, home)]));

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const stale = [];
  for (const [target, text] of Object.entries(build())) {
    const file = path.join(HOME, target);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (current === text) {
      continue;
    }
    stale.push(target);
    if (!check) {
      fs.mkdirSync(path.dirname(file), {recursive: true});
      fs.writeFileSync(file, text, {mode: target.endsWith('.mjs') ? 0o755 : 0o644});
    }
  }
  console.log(stale.length ? `${check ? 'Not as built' : 'Built'}: ${stale.join(', ')}` : 'The plugins are as built.');
  process.exitCode = check && stale.length ? 1 : 0;
}
